"""Names of every wearable item, from the game's own item tables (db2 cache of the foreverman skill),
so the wardrobe can search by name without asking the server for thousands of items.

    py -3 names.py        writes ../Names.lua
"""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
CACHE = Path.home() / ".claude/skills/foreverman/tools/db2cache"
WEARABLE = {1, 3, 5, 6, 7, 8, 9, 10, 13, 14, 15, 16, 17, 20, 21, 22, 23, 26}


def newest(name):
    for build in sorted((p for p in CACHE.iterdir() if (p / name).exists()), key=lambda p: [int(x) for x in p.name.split(".")], reverse=True):
        return build / name
    raise SystemExit(f"{name} not cached: py -3 db2.py table {name[:-4]} ID=1")


def main():
    with open(newest("Item.csv"), encoding="utf-8") as f:
        wearable = {int(r["ID"]) for r in csv.DictReader(f) if int(r["InventoryType"] or 0) in WEARABLE}
    names = {}
    with open(newest("ItemSparse.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            i = int(r["ID"])
            if i in wearable and r["Display_lang"]:
                names[i] = r["Display_lang"]
    lines = ["-- Generated by tools/names.py from the game's own item tables. Do not edit.",
             "local _, ns = ...", "ns.NAMES = {"]
    for i in sorted(names):
        text = names[i].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    [{i}] = "{text}",')
    lines.append("}")
    (HERE.parent / "Names.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(names)} names of {len(wearable)} wearable items")


if __name__ == "__main__":
    main()
