"""Class-only items (tier pieces and the like): which of the nine Forever classes may wear each
wearable item, from the AllowableClass mask of the game's own item table.

    py -3 classes.py      writes ../Classes.lua
"""
import csv
from pathlib import Path

from names import newest, WEARABLE

HERE = Path(__file__).resolve().parent
# class id - 1 = bit: warrior 1, paladin 2, hunter 4, rogue 8, priest 16, shaman 64, mage 128,
# warlock 256, druid 1024
FOREVER = 1 | 2 | 4 | 8 | 16 | 64 | 128 | 256 | 1024


def main():
    with open(newest("Item.csv"), encoding="utf-8") as f:
        wearable = {int(r["ID"]) for r in csv.DictReader(f) if int(r["InventoryType"] or 0) in WEARABLE}
    masks = {}
    with open(newest("ItemSparse.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            i = int(r["ID"])
            mask = int(r["AllowableClass"] or -1)
            if i not in wearable or mask == -1:
                continue
            mask &= FOREVER
            if mask != FOREVER:
                masks[i] = mask
    lines = ["-- Generated by tools/classes.py from the game's own item tables. Do not edit.",
             "-- itemID -> the classes that may wear it (bit = class id - 1); items any class may wear are left out.",
             "local _, ns = ...", "ns.ITEM_CLASSES = {"]
    for i in sorted(masks):
        lines.append(f"    [{i}] = {masks[i]},")
    lines.append("}")
    (HERE.parent / "Classes.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(masks)} class-only items of {len(wearable)} wearable items")


if __name__ == "__main__":
    main()
