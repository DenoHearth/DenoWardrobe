"""The look of every wearable item, from the game's own tables (db2 cache of the foreverman skill):
item -> its appearance source (ItemModifiedAppearance.ID) and appearance (ItemAppearanceID), plus
the item quality where ItemSparse has it.

Why: C_TransmogCollection.GetItemInfo(itemID) answers nothing for an item the client has not
loaded from the server yet, and a model told to TryOn("item:N") for such an item stays empty.
A source id needs no server: the game's own wardrobe dresses thousands of uncollected looks
from it. With this table every tile is dressed at once, also right after /reload or a new login.

    py -3 looks.py        writes ../Looks.lua (newest cached build)

Refresh the tables first when the client has a new build:
    py -3 ~/.claude/skills/foreverman/tools/db2.py table ItemModifiedAppearance ID=1
    (same for Item, ItemAppearance, ItemSparse)
"""
import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CACHE = Path.home() / ".claude/skills/foreverman/tools/db2cache"
# Items nobody can have: placeholders and dead test items by name, and anything above the
# level cap (Forever stops at 60; "[PH] Shining Dawn Coif" needs 100). AtlasLoot's crafting
# lists carry some of them.
JUNK_NAME = re.compile(r"\[PH\]|DEPRECATED|^Deprecated |^Test |\bTEST\b|^Monster - |^QA ")
LEVEL_CAP = 60
WEARABLE = {1, 3, 4, 5, 6, 7, 8, 9, 10, 13, 14, 15, 16, 17, 19, 20, 21, 22, 23, 26}


def newest(name):
    builds = sorted((p for p in CACHE.iterdir() if (p / name).exists()),
                    key=lambda p: [int(x) for x in p.name.split(".")], reverse=True)
    if not builds:
        raise SystemExit(f"{name} not cached: py -3 db2.py table {name[:-4]} ID=1")
    return builds[0] / name


def rows(name):
    with open(newest(name), encoding="utf-8") as f:
        yield from csv.DictReader(f)


def main():
    wearable = {int(r["ID"]) for r in rows("Item.csv") if int(r["InventoryType"] or 0) in WEARABLE}
    shown = {int(r["ID"]) for r in rows("ItemAppearance.csv") if int(r["ItemDisplayInfoID"] or 0) != 0}
    quality, junk = {}, set()
    for r in rows("ItemSparse.csv"):
        item = int(r["ID"])
        quality[item] = int(r["OverallQualityID"] or 1)
        if JUNK_NAME.search(r["Display_lang"] or "") or int(r["RequiredLevel"] or 0) > LEVEL_CAP:
            junk.add(item)
    best = {}      # item -> (modifier, order, source, appearance): the plain look (modifier 0) first
    for r in rows("ItemModifiedAppearance.csv"):
        item, appearance = int(r["ItemID"]), int(r["ItemAppearanceID"])
        if item not in wearable or appearance not in shown:
            continue
        key = (int(r["ItemAppearanceModifierID"]), int(r["OrderIndex"]), int(r["ID"]), appearance)
        if item not in best or key < best[item]:
            best[item] = key
    build = newest("ItemModifiedAppearance.csv").parent.name
    lines = [f"-- Generated by tools/looks.py from the game's own item tables, build {build}. Do not edit.",
             "-- [itemID] = { appearance source, appearance, quality or nil }",
             "local _, ns = ...", f'ns.LOOKS_BUILD = "{build}"', "ns.LOOKS = {"]
    for item in sorted(best):
        _, _, source, appearance = best[item]
        q = quality.get(item)
        lines.append(f"[{item}]={{{source},{appearance}{',' + str(q) if q is not None else ''}}},")
    lines.append("}")
    # wearable items this build knows that have no look at all; an item NOT in the game's tables
    # here is newer than this file (AtlasLoot added it) and is kept: its look comes from the game
    nolook = sorted(wearable - set(best))
    lines.append("-- wearable items of this build without any look: nothing to show on a model")
    lines.append("ns.NOLOOK = {" + ",".join(f"[{i}]=true" for i in nolook) + "}")
    lines.append("-- placeholders, dead test items and items above the level cap: never shown")
    lines.append("ns.JUNK = {" + ",".join(f"[{i}]=true" for i in sorted(junk & wearable)) + "}")
    (HERE.parent / "Looks.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"build {build}: {len(best)} wearable items with a look, of {len(wearable)} wearable items; "
          f"{sum(1 for i in best if i in quality)} with a quality; {len(junk & wearable)} junk")


if __name__ == "__main__":
    main()
