"""Looks the loot addons do not list, from the local test server's world database.

Every wearable item (by the game's own Item table) that a creature drops, a chest holds, a vendor
sells or a quest gives, with one short source line each. Written to ../ServerLooks.lua; the
wardrobe adds these after AtlasLoot Forever's and skips any item AtlasLoot already has.

    py -3 serverlooks.py            (the test database must run: C:/Dev/forever-server)

Only items the game client knows are kept (its Item table, db2 cache of the foreverman skill).
"""
import csv
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ITEM_CSV = Path.home() / ".claude/skills/foreverman/tools/db2cache/1.60.1.70374/Item.csv"
ITEM_CSV_OLD = Path.home() / ".claude/skills/foreverman/tools/db2cache/1.60.1.70338/Item.csv"
MYSQL = Path(r"C:\Users\Deniz\Desktop\WoW\ForeverRepack\mysql\bin\mysql.exe")
# InventoryType values that show on a character (shirt and tabard left out, as in the wardrobe)
WEARABLE = {1, 3, 5, 6, 7, 8, 9, 10, 13, 14, 15, 16, 17, 20, 21, 22, 23, 26}


def sql(query):
    out = subprocess.run([str(MYSQL), "-uroot", "-P3317", "-h127.0.0.1", "-N", "-B", "--default-character-set=utf8mb4", "-e", query],
                         capture_output=True, text=True, encoding="utf-8", errors="replace")
    if out.returncode:
        raise SystemExit(out.stderr)
    return [line.split("\t") for line in out.stdout.splitlines() if line]


def wearable_items():
    path = ITEM_CSV if ITEM_CSV.exists() else ITEM_CSV_OLD
    with open(path, encoding="utf-8") as f:
        return {int(r["ID"]) for r in csv.DictReader(f) if int(r["InventoryType"] or 0) in WEARABLE}


def lua_text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    items = wearable_items()
    found = {}            # itemID -> (rank, label); lower rank wins

    def offer(item, rank, label):
        item = int(item)
        if item in items and (item not in found or rank < found[item][0]):
            found[item] = (rank, label)

    for item, title in sql("select i, LogTitle from (select ID, LogTitle, RewardItem1 i from world.quest_template union all "
                           "select ID, LogTitle, RewardItem2 from world.quest_template union all select ID, LogTitle, RewardItem3 from world.quest_template union all "
                           "select ID, LogTitle, RewardItem4 from world.quest_template union all select ID, LogTitle, RewardChoiceItemID1 from world.quest_template union all "
                           "select ID, LogTitle, RewardChoiceItemID2 from world.quest_template union all select ID, LogTitle, RewardChoiceItemID3 from world.quest_template union all "
                           "select ID, LogTitle, RewardChoiceItemID4 from world.quest_template union all select ID, LogTitle, RewardChoiceItemID5 from world.quest_template union all "
                           "select ID, LogTitle, RewardChoiceItemID6 from world.quest_template) q where i > 0"):
        offer(item, 1, f"Quest: {title}")
    for item, name in sql("select v.item, c.name from world.npc_vendor v join world.creature_template c on c.entry = v.entry where v.item > 0"):
        offer(item, 2, f"Vendor: {name}")
    # creature drops, one reference level deep; the best chance names the source
    drops = sql("select l.Item, c.name, l.Chance, l.ItemType from world.creature_template_difficulty d "
                "join world.creature_template c on c.entry = d.Entry join world.creature_loot_template l on l.Entry = d.LootID "
                "where d.LootID > 0 and exists (select 1 from world.creature s where s.id = c.entry)")
    refs = {}
    for entry, item in sql("select Entry, Item from world.reference_loot_template where ItemType = 0"):
        refs.setdefault(entry, []).append(item)
    best = {}
    for item, name, chance, kind in drops:
        targets = refs.get(item, []) if kind == "1" else [item]
        for target in targets:
            c = float(chance or 0)
            if int(target) in items and (target not in best or c > best[target][0]):
                best[target] = (c, name)
    for item, (chance, name) in best.items():
        offer(item, 3, f"Drop: {name}")
    for item, name in sql("select l.Item, g.name from world.gameobject_template g join world.gameobject_loot_template l on l.Entry = g.Data1 "
                          "where g.type = 3 and g.Data1 > 0 and l.ItemType = 0"):
        offer(item, 4, f"Chest: {name}")

    lines = ["-- Generated by tools/serverlooks.py from the local test server's world database. Do not edit.",
             "-- Wearable items the game client knows, with one source line each.",
             "local _, ns = ...", "ns.SERVER_LOOKS = {"]
    for item in sorted(found):
        lines.append(f"    [{item}] = {lua_text(found[item][1])},")
    lines.append("}")
    (HERE.parent / "ServerLooks.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    kinds = {}
    for rank, _ in found.values():
        kinds[rank] = kinds.get(rank, 0) + 1
    print(f"{len(found)} looks: quests {kinds.get(1, 0)}, vendors {kinds.get(2, 0)}, drops {kinds.get(3, 0)}, chests {kinds.get(4, 0)}")


if __name__ == "__main__":
    main()
